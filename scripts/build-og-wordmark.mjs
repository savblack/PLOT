#!/usr/bin/env node
/**
 * Emit the plot wordmark outlines for the og-card Edge Function.
 *
 * packages/core/wordmark.js is the single source of truth for the wordmark
 * paths, but `supabase functions deploy` bundles only what sits under
 * supabase/functions, so the function cannot import it by relative path. This
 * writes the three values the card renderer needs to a generated module
 * beside the function (same approach as footer.generated.ts).
 *
 * Usage:
 *   node scripts/build-og-wordmark.mjs          # rewrite the generated module
 *   node scripts/build-og-wordmark.mjs --check  # CI: exit 1 if out of sync
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { WORDMARK_EM, WORDMARK_PATH, WORDMARK_VIEWBOX } from '../packages/core/wordmark.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'supabase/functions/og-card/wordmark.generated.ts');

const generated = `// @generated by scripts/build-og-wordmark.mjs from packages/core/wordmark.js
// Do not edit by hand. Run pnpm run og-wordmark after changing the wordmark.
export const WORDMARK_PATH = ${JSON.stringify(WORDMARK_PATH)};
export const WORDMARK_VIEWBOX = ${JSON.stringify(WORDMARK_VIEWBOX)};
export const WORDMARK_EM = ${JSON.stringify(WORDMARK_EM)} as const;
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(output, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== generated) {
    console.error('og-card wordmark is out of sync. Run pnpm run og-wordmark.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, generated);
}
