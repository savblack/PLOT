#!/usr/bin/env node
// Bundle the shared import engine for the import-worker edge function.
//
// WHY: the worker has to run the same parse / match / plan / write code the
// apps run in the page, or a background import would finish differently from
// a foreground one. Edge functions cannot import packages/core (the deploy
// bundler only sees supabase/functions), so this writes a self-contained ESM
// bundle into _shared. `pnpm run lint` runs it with --check so the bundle can
// never fall behind its source.
//
// @supabase/supabase-js stays external (as the npm: specifier edge functions
// use): the worker injects its own service role client through
// configure({ supabaseClient }), so nothing in the bundle constructs one.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'packages/core/importEngine.js');
const output = join(root, 'supabase/functions/_shared/importEngine.generated.js');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  // The worker resolves supabase-js the way every edge function does.
  alias: { '@supabase/supabase-js': 'npm:@supabase/supabase-js@2' },
  external: ['npm:@supabase/supabase-js@2', 'react'],
  legalComments: 'none',
  logLevel: 'silent',
  absWorkingDir: root,
});
const header = `// @generated by scripts/build-import-engine.mjs from packages/core/importEngine.js
// Do not edit by hand. Run pnpm run import-engine after changing the import pipeline.
// deno-lint-ignore-file
`;
const generated = header + result.outputFiles[0].text;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(output, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== generated) {
    console.error('Import engine bundle is out of sync. Run pnpm run import-engine.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, generated);
  console.log(`wrote ${output} (${(generated.length / 1024).toFixed(0)} KB)`);
}
