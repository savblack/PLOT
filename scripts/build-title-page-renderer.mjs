#!/usr/bin/env node
// Keep Cloudflare's title HTML identical to the existing Supabase renderer.
// The source function remains available as a fallback if the TMDB Worker fails.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'supabase/functions/title-page/index.ts'), 'utf8');
const seoText = readFileSync(join(root, 'supabase/functions/_shared/seoText.ts'), 'utf8');
const output = join(root, 'apps/website/functions/_lib/titleRenderer.generated.js');
const between = (start, end) => {
  const from = source.indexOf(start);
  const to = source.indexOf(end, from + start.length);
  if (from < 0 || to < 0) throw new Error(`Title renderer markers missing: ${start}`);
  return source.slice(from, to);
};

const helpers = (between('const SITE =', 'function notFound()') + between('type Prov =', 'type SitemapTitle ='))
  .replace('function page(title: string, head: string, body: string, status = 200, cache = true)',
    "function page(title: string, head: string, body: string, status = 200, cache = true, footerHtml = '')")
  .replace('${FOOTER_HTML}', '${footerHtml}');
const body = between('  const isMovie =', '\n});')
  // The sampled Supabase path records titles for the sitemap. The Cloudflare
  // renderer has no service role credential and must not make this write.
  .replace(/\n  recordTitles\(\[\n[\s\S]*?\n  \]\);\n/, '\n')
  .replace('return page(metaTitle, head, body);', 'return page(metaTitle, head, body, 200, true, footerHtml);');
if (body.includes('recordTitles(')) throw new Error('Title index write was not removed from Cloudflare renderer');
const moduleSource = `${seoText}\n${helpers}\nexport function renderTitlePage(data: any, type: 'movie' | 'tv', id: number, slug: string, region: string, footerHtml: string) {\n${body}\n}\n`;
const generated = `// @generated by scripts/build-title-page-renderer.mjs from supabase/functions/title-page/index.ts
// Do not edit by hand. Run pnpm run title-renderer after editing the source renderer.
${ts.transpileModule(moduleSource, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
}).outputText}`;

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    console.error('Title page renderer is out of sync. Run pnpm run title-renderer.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, generated);
}
