// Resolves a curated list's titles to TMDB ids and writes
// packages/core/curatedListData/<id>.js. IDs are never typed by hand
// (AGENTS.md): each comes from a TMDB search response. Review the printed
// table before committing; a wrong match shows as a differing title or year.
//
//   node --env-file=.env scripts/resolve-curated-list.mjs scripts/curated-lists/<id>.json
//
// Input: { id, title, blurb, source: { name, url }, entries: [{ rank, query, year, media_type }] }
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const input = process.argv[2];
if (!input || !process.env.TMDB_API_KEY) {
  console.error('usage: node --env-file=.env scripts/resolve-curated-list.mjs <spec.json> (needs TMDB_API_KEY)');
  process.exit(1);
}
const spec = JSON.parse(readFileSync(input, 'utf8'));
const norm = s => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

async function search(entry) {
  const kind = entry.media_type === 'movie' ? 'movie' : 'tv';
  const yearKey = kind === 'tv' ? 'first_air_date_year' : 'year';
  const params = new URLSearchParams({ api_key: process.env.TMDB_API_KEY, query: entry.query, [yearKey]: String(entry.year) });
  const res = await fetch(`https://api.themoviedb.org/3/search/${kind}?${params}`);
  if (!res.ok) throw new Error(`${entry.query}: HTTP ${res.status}`);
  let { results } = await res.json();
  if (!results.length) {
    // TMDB dates a show by its first season; a later season (Twin Peaks: The
    // Return) or a rebooted series can miss the year. Retry on the name alone.
    params.delete(yearKey);
    results = (await (await fetch(`https://api.themoviedb.org/3/search/${kind}?${params}`)).json()).results;
  }
  const name = r => r.name || r.title;
  const hit = results.find(r => norm(name(r)) === norm(entry.query)) || results[0];
  return hit && { kind, hit };
}

const out = [];
for (const entry of spec.entries) {
  const found = await search(entry);
  if (!found) { console.log(`${entry.rank}. NO MATCH  ${entry.query} (${entry.year})`); continue; }
  const { kind, hit } = found;
  const title = hit.name || hit.title;
  const date = hit.first_air_date || hit.release_date || '';
  const yearOff = Math.abs(Number(date.slice(0, 4)) - entry.year) > 1;
  const flag = norm(title) === norm(entry.query) && !yearOff ? '' : '  <-- CHECK';
  console.log(`${entry.rank}. ${entry.query} (${entry.year}) -> ${title} (${date.slice(0, 4)}) ${hit.id}${flag}`);
  out.push({ rank: entry.rank, tmdb_id: hit.id, media_type: kind, title, poster_path: hit.poster_path || null, genre_ids: hit.genre_ids || [] });
}

const file = resolve(dirname(new URL(import.meta.url).pathname), '../packages/core/curatedListData', `${spec.id}.js`);
mkdirSync(dirname(file), { recursive: true });
const { entries: _omit, ...meta } = spec;
writeFileSync(file, `// Generated by scripts/resolve-curated-list.mjs. Do not edit by hand.\nexport default ${JSON.stringify({ ...meta, entries: out }, null, 2)};\n`);
console.log(`\nwrote ${out.length}/${spec.entries.length} entries to ${file}`);
