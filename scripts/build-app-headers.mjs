#!/usr/bin/env node
/**
 * Copy the web app's Content-Security-Policy into apps/web/public/_headers.
 *
 * WHY: every Pages Function call counts toward the Cloudflare account's free
 * allowance of 100,000 Workers requests a day, and that allowance ran out on
 * 2026-11-11. The app's middleware (functions/_middleware.js) used to run on
 * every page load only to add this header. apps/web/public/_routes.json now
 * sends just the real Function routes there, so ordinary pages get their policy
 * from the static _headers file instead.
 *
 * The policy stays defined once, in functions/_middleware.js (the Function
 * routes still need it there). This script writes the same text into a marked
 * block of _headers, keyed by host so previews get the staging-aware policy
 * and noindex, as the middleware does.
 *
 * Usage:  node scripts/build-app-headers.mjs          rewrite the block
 *         node scripts/build-app-headers.mjs --check  fail if it is stale (lint)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CSP, PREVIEW_CSP } from '../functions/_middleware.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const HEADERS_PATH = resolve(ROOT, 'apps/web/public/_headers');
const BEGIN = '# BEGIN app-csp: generated by scripts/build-app-headers.mjs from functions/_middleware.js. Do not edit by hand.';
const END = '# END app-csp';
// Cloudflare Pages ignores a _headers line longer than this.
const MAX_LINE = 2000;

// Every host gets PREVIEW_CSP from the main `/*` rule (the one right after the
// block), so a host no rule names still has a policy: the middleware gave every
// host other than app.theplot.tv this one. It must be a line of that rule, not a
// second `/*` rule: Pages keeps only the last rule for an identical path.
const FALLBACK = `  Content-Security-Policy: ${PREVIEW_CSP}`;

const block = [
  BEGIN,
  // Production adds the stricter policy. A browser enforces both headers, and
  // CSP differs from PREVIEW_CSP only by leaving staging out of connect-src,
  // so production's effective policy is CSP.
  'https://app.theplot.tv/*',
  `  Content-Security-Policy: ${CSP}`,
  '',
  // Production-branch and per-branch preview deployments stay out of search.
  'https://:project.pages.dev/*',
  '  X-Robots-Tag: noindex, nofollow',
  '',
  'https://:version.:project.pages.dev/*',
  '  X-Robots-Tag: noindex, nofollow',
  END,
].join('\n');

// The intersection argument above holds only while CSP is PREVIEW_CSP with
// sources removed. If that ever changes, fail rather than ship a production
// policy that silently differs from the middleware's.
const directives = (policy) => new Map(policy.split(';').map((d) => d.trim().split(/\s+/)).map(([name, ...src]) => [name, src]));
const prod = directives(CSP);
const preview = directives(PREVIEW_CSP);
for (const [name, src] of prod) {
  const wider = preview.get(name);
  if (!wider || src.some((s) => !wider.includes(s))) {
    console.error(`build-app-headers: CSP directive "${name}" is not a subset of PREVIEW_CSP's, so enforcing both would not equal CSP.`);
    process.exit(1);
  }
}
if ([...preview.keys()].some((name) => !prod.has(name))) {
  console.error('build-app-headers: PREVIEW_CSP has a directive CSP lacks; enforcing both would be stricter than CSP.');
  process.exit(1);
}

for (const line of [...block.split('\n'), FALLBACK]) {
  if (line.length > MAX_LINE) {
    console.error(`build-app-headers: a generated line is ${line.length} characters; Pages ignores lines over ${MAX_LINE}.`);
    process.exit(1);
  }
}

const current = readFileSync(HEADERS_PATH, 'utf8');
const start = current.indexOf(BEGIN);
const stop = current.indexOf(END);
if (start === -1 || stop === -1 || stop < start) {
  console.error(`build-app-headers: ${HEADERS_PATH} is missing the "${BEGIN}" / "${END}" markers.`);
  process.exit(1);
}
// After the block: a blank line, then the main `/*` rule, whose first header
// line is the generated fallback policy.
let rest = current.slice(stop + END.length);
const MAIN = '\n\n/*\n';
if (!rest.startsWith(MAIN)) {
  console.error(`build-app-headers: the main "/*" rule must follow "${END}" after one blank line.`);
  process.exit(1);
}
rest = rest.slice(MAIN.length);
if (rest.startsWith('  Content-Security-Policy:')) rest = rest.slice(rest.indexOf('\n') + 1);
const next = current.slice(0, start) + block + MAIN + FALLBACK + '\n' + rest;

if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('build-app-headers: apps/web/public/_headers is out of date with functions/_middleware.js. Run: node scripts/build-app-headers.mjs');
    process.exit(1);
  }
} else if (next !== current) {
  writeFileSync(HEADERS_PATH, next);
  console.log('build-app-headers: updated apps/web/public/_headers');
}
