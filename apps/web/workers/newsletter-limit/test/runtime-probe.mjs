import { onRequest } from '../../../../website/functions/api/newsletter.js';
import assert from 'node:assert/strict';
const origin = process.env.PLOT_LIMITER_ORIGIN || 'http://127.0.0.1:8793';
const suffix = Number(process.env.PLOT_TEST_IP_SUFFIX || Math.floor(Math.random() * 100) + 100);
const realFetch = globalThis.fetch;
let upstreamCalls = 0;
globalThis.fetch = async () => { upstreamCalls++; return Response.json({ ok: true }); };
const env = { NEWSLETTER_EDGE_LIMITER: { fetch: req => realFetch(`${origin}/check`, { method: req.method, headers: req.headers }) } };
const request = ip => new Request('https://theplot.tv/api/newsletter', { method: 'POST', headers: { 'CF-Connecting-IP': ip, 'content-type': 'application/json' }, body: '{"email":"local-test@example.invalid"}' });
const statuses=[];
for(let i=0;i<6;i++) statuses.push((await onRequest({request:request(`192.0.2.${suffix}`),env})).status);
assert.deepEqual(statuses,[200,200,200,200,200,429]);
assert.equal(upstreamCalls,5);
const blocked=await onRequest({request:request(`192.0.2.${suffix}`),env});
assert.equal(blocked.status,429);
assert.ok(Number(blocked.headers.get('retry-after'))>590);
const before=upstreamCalls;
const parallel=await Promise.all(Array.from({length:10},()=>onRequest({request:request(`192.0.2.${suffix + 1}`),env})));
assert.equal(parallel.filter(r=>r.status===200).length,5);
assert.equal(parallel.filter(r=>r.status===429).length,5);
assert.equal(upstreamCalls-before,5);
const result={sequential_statuses:statuses,supabase_calls_for_six_requests:5,repeated_block_status:blocked.status,retry_after:blocked.headers.get('retry-after'),concurrent_requests:10,concurrent_allowed:5,concurrent_blocked:5,real_supabase_requests:0};
console.log(JSON.stringify(result,null,2));
