// Where share-link og:image tags point.
//
// Branded 1200×630 cards come from app.theplot.tv/og (functions/og.js), which
// caches at Cloudflare's edge and proxies the og-card Supabase Edge Function
// that draws them with Satori. That function replaced the plot-og Cloudflare
// Worker, which the free Workers plan's 10ms CPU ceiling killed on every
// render (2026-09-18 to 2026-10-15, during which titles used TMDB backdrops
// and everything else the static card).
//
// The static card is the fallback for pages with no card variant (watch-with)
// and for the proxy itself when a render fails.
export const CARD = { width: 1200, height: 630 };

/**
 * The branded card for a share target.
 * @param {string} host
 * @param {{ u?: string } | { list?: string } | { post?: string } | { type?: string, id?: number | string }} params
 */
export const ogCard = (host, params) => `https://${host}/og?${new URLSearchParams(params)}`;

/** The static brand card. Generated by scripts/generate-app-og-image.mjs. */
export const staticCard = (host) => `https://${host}/og-image.png`;
